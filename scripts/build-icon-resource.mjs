#!/usr/bin/env node
/**
 * Compile the app's own icons into a GResource and write it into the bundle as
 * base64, so the shipped artefact stays a SINGLE file.
 *
 * `gjsify build` has no resource step and `app/dist` is gitignored, so a
 * `troedler.gresource` sitting next to the bundle would be a second file to lose
 * — and a missing one is a white rectangle on a button rather than an error. The
 * resource therefore travels INSIDE the TypeScript: this script compiles it once,
 * on a machine that has `glib-compile-resources`, and writes a generated module
 * the bundler picks up like any other source.
 *
 * The generated module also carries the SHA-256 of the SVG it was built from, so
 * `scripts/guard-icon-names.mjs` can prove the two agree WITHOUT this tool: CI
 * needs nothing but Node, and an icon edited without regenerating is a failed
 * build rather than a stale blob nobody notices.
 *
 *   node scripts/build-icon-resource.mjs          # write
 *   node scripts/build-icon-resource.mjs --check  # verify, exit 1 on drift
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RESOURCE_DIR = join(root, 'app/src/frontends/gui/resources');
const XML = join(RESOURCE_DIR, 'troedler.gresource.xml');
const OUT = join(root, 'app/src/frontends/gui/icon-resource.ts');
const CHECK = process.argv.includes('--check');

/** The `prefix=` of the single `<gresource>` in the XML — the icon theme path. */
const PREFIX = /prefix="([^"]+)"/.exec(readFileSync(XML, 'utf8'))?.[1] ?? null;
if (!PREFIX) {
  console.error(`${XML}: no <gresource prefix="…"> found — nothing to register.`);
  process.exit(1);
}

const work = mkdtempSync(join(tmpdir(), 'troedler-icons-'));
try {
  const target = join(work, 'troedler.gresource');
  execFileSync(
    'glib-compile-resources',
    [`--sourcedir=${RESOURCE_DIR}`, `--target=${target}`, XML],
    { stdio: ['ignore', 'inherit', 'inherit'] },
  );

  const blob = readFileSync(target);
  // The hash is of the SOURCE, not of the blob: glib-compile-resources output is
  // not required to be byte-stable across versions, and a guard that fails on a
  // toolchain bump would be a guard that gets disabled.
  const source = readFileSync(join(RESOURCE_DIR, 'troedler-filter-symbolic.svg'));
  const sha = createHash('sha256').update(source).digest('hex');
  const b64 = blob.toString('base64');

  const module = `/**
 * The app's own icons, as a GResource compiled into this module.
 *
 * GENERATED by \`scripts/build-icon-resource.mjs\` — do not edit. Run that script
 * after changing anything in \`app/src/frontends/gui/resources/\`.
 *
 * It is base64 in a TypeScript file rather than a \`.gresource\` next to the bundle
 * because the bundle is the artefact: one file, nothing beside it to install,
 * nothing to lose. \`icons.ts\` registers it with the icon theme at startup.
 */

/** Where \`Gtk.IconTheme\` must look to find them. */
export const ICON_RESOURCE_PREFIX = '${PREFIX}';

/**
 * SHA-256 of the SVG this was compiled from.
 *
 * Carried so \`scripts/guard-icon-names.mjs\` can check the resource against its
 * source on a machine that has no \`glib-compile-resources\` — which is every CI
 * runner that is not this workstation.
 */
export const ICON_SOURCE_SHA256 = '${sha}';

/** The compiled resource, base64. ${blob.length} bytes before encoding. */
export const ICON_RESOURCE_BASE64 =
  '${b64.replace(/(.{100})/g, "$1' +\n  '")}';
`;

  if (CHECK) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== module) {
      console.error(
        `${OUT} is out of date with app/src/frontends/gui/resources/.\n` +
          'Run: node scripts/build-icon-resource.mjs',
      );
      process.exit(1);
    }
    console.log(`icon-resource.ts is current (${sha.slice(0, 12)}…, ${blob.length} bytes).`);
  } else {
    writeFileSync(OUT, module);
    console.log(`wrote ${OUT} — ${blob.length} bytes of GResource, source ${sha.slice(0, 12)}…`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
