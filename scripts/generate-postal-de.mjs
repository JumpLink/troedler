#!/usr/bin/env node
/**
 * Regenerate `packages/core/src/geo/postal-de.ts` from GeoNames' postal-code dump.
 *
 *   curl -O https://download.geonames.org/export/zip/DE.zip && unzip DE.zip DE.txt
 *   node scripts/generate-postal-de.mjs DE.txt
 *
 * GeoNames lists a postcode once per place it covers, with a coordinate each,
 * and some rows are not places at all: 10875 is a Berlin large-customer code
 * whose rows sit in Stuttgart. A mean over those rows would put the centroid in
 * the middle of nowhere, so each axis takes the MEDIAN.
 *
 * Coordinates are stored in hundredths of a degree (about 1 km). The radius
 * filter compares against 5 to 100 km, so a finer table would only buy digits
 * the postcode centroid cannot back up anyway.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const input = process.argv[2];
if (!input) {
  console.error('usage: generate-postal-de.mjs <DE.txt>');
  process.exit(2);
}

const byCode = new Map();
for (const line of readFileSync(input, 'utf8').split('\n')) {
  const cols = line.split('\t');
  if (cols.length < 11 || cols[0] !== 'DE') continue;
  const lat = Number.parseFloat(cols[9]);
  const lon = Number.parseFloat(cols[10]);
  if (!/^\d{5}$/.test(cols[1]) || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const rows = byCode.get(cols[1]) ?? { lat: [], lon: [] };
  rows.lat.push(lat);
  rows.lon.push(lon);
  byCode.set(cols[1], rows);
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  const mid = s.length >> 1;
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};

const entries = [...byCode.keys()]
  .sort()
  .map((code) => {
    const { lat, lon } = byCode.get(code);
    return `${code}:${Math.round(median(lat) * 100)}:${Math.round(median(lon) * 100)}`;
  });

const out = `/**
 * German postcode centroids — generated by \`scripts/generate-postal-de.mjs\`, do not edit.
 *
 * Source: GeoNames postal codes for Germany, https://download.geonames.org/export/zip/DE.zip,
 * licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Changed: one
 * centroid per postcode (median of the places listed for it), rounded to 0.01°.
 * ${entries.length} postcodes. Attribution also in docs/geodaten.md.
 *
 * Entries are \`<plz>:<lat×100>:<lon×100>\`, joined by \`;\`.
 */
export const POSTAL_DE = '${entries.join(';')}';
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '../packages/core/src/geo/postal-de.ts');
writeFileSync(target, out);
console.log(`${entries.length} postcodes, ${out.length} bytes → ${target}`);
